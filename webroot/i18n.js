// Resolve the UI language: a saved choice wins, then the device languages, then English.
window.DD_resolveLang = function (saved) {
  var codes = window.DD_LANGS.map(function (l) { return l.code; });
  if (codes.indexOf(saved) >= 0) return saved;
  var prefs = (navigator.languages && navigator.languages.length) ? navigator.languages : [navigator.language || ''];
  for (var i = 0; i < prefs.length; i++) {
    var base = String(prefs[i] || '').toLowerCase().split('-')[0];
    if (codes.indexOf(base) >= 0) return base;
  }
  return 'en';
};

window.DD_applyLang = function (code) {
  var meta = window.DD_LANGS.filter(function (l) { return l.code === code; })[0] || window.DD_LANGS[0];
  var root = document.documentElement;
  root.dataset.lang = meta.code;
  root.lang = meta.locale;
  root.dir = meta.dir;
  return meta;
};
